using System.Diagnostics.CodeAnalysis;

namespace PaymentGateway.Common.Results;

/// <summary>
/// Either a value or an <see cref="Error"/>. Used for expected outcomes (e.g. the bank being unavailable)
/// so callers must handle them explicitly instead of catching exceptions.
/// </summary>
public sealed class Result<T>
{
    private Result(T? value, Error? error)
    {
        Value = value;
        Error = error;
    }

    public T? Value { get; }

    public Error? Error { get; }

    [MemberNotNullWhen(true, nameof(Value))]
    [MemberNotNullWhen(false, nameof(Error))]
    public bool IsSuccess => Error is null;

    public static Result<T> Success(T value) => new(value, null);

    public static Result<T> Failure(Error error) => new(default, error);

    public static implicit operator Result<T>(T value) => Success(value);

    public static implicit operator Result<T>(Error error) => Failure(error);
}
